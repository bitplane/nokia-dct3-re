"""Cross-check the external C++ access decoder against independent Python coding."""
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

from tools.gsm_rach_signal import HEADER, coded_access


class RachCppTest(unittest.TestCase):
    def test_all_access_octets_and_corruptions(self):
        compiler = shutil.which('c++')
        if not compiler:
            self.skipTest('C++ compiler unavailable')
        root = Path(__file__).resolve().parents[1]
        source = ['#include "gsm_rach.h"', '#include <cassert>', 'int main() {']
        for bsic in (0, 42, 63):
            for ra in range(256):
                bits = (0,) * 9 + HEADER + coded_access(ra, bsic) + (0,) * 3
                bits += (1,) * (180 - len(bits))
                words = [sum(bits[word * 12 + bit] << bit for bit in range(12))
                         for word in range(15)]
                packed = ','.join(hex(word) for word in words)
                source.append('{ std::array<std::uint16_t,15> w{' + packed + '};'
                              f' assert(gsm::rach::decode_p27(w,{bsic}) == {ra});'
                              f' assert(!gsm::rach::decode_p27(w,{bsic ^ 1}));' + '}')
        # Captured native transaction is not generated by either encoder here.
        source.append('std::array<std::uint16_t,15> w{0xb9ff,0x1a4b,0x33fd,0x0ab3,'
                      '0x9c78,0x1f89,0xaf9f,0x033a,0xfffe,0x1fff,0xffff,0x1fff,0xffff,0xffff,0x01ff};')
        source.append('assert(gsm::rach::decode_p27(w,42) == 11);')
        source.append('for(unsigned bit=58; bit<94; ++bit) {'
                      'auto bad=w; bad[bit/12]^=1U<<(bit%12);'
                      'assert(!gsm::rach::decode_p27(bad,42)); }')
        source.append('w[94/12]^=1U<<(94%12); assert(!gsm::rach::decode_p27(w,42));'
                      'assert(!gsm::rach::decode_p27(w,64)); }')
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory)
            (path / 'test.cpp').write_text('\n'.join(source))
            subprocess.run([compiler, '-std=c++17', '-O0', '-Wall', '-Wextra', '-Werror',
                            '-I', str(root / 'driver'), str(path / 'test.cpp'),
                            '-o', str(path / 'test')], check=True, capture_output=True, text=True)
            subprocess.run([str(path / 'test')], check=True, capture_output=True, text=True)


if __name__ == '__main__':
    unittest.main()
