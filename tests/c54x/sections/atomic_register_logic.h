#include "c54x_section_common.h"
namespace c54x_test {
inline std::vector<clocked_register_case> section_cases()
{
	struct row { u16 opcode,literal; bool extended; u64 a,b,out_a,out_b; u16 st0,flags,mask; };
	constexpr row rows[]{
		{0xf490,0,false,0xab80000002ULL,0x1234,0xc0000001,0x1234,0x800,0,0x800},
		{0xf590,0,false,0xc0000001,0xff00000001ULL,0xc0000001,0,0,0x800,0x800},
		{0xf3b0,0,false,0x1234,0xff80000001ULL,0x1234,0xff80ff8001ULL,0x800,0x800,0x800},
		{0xf3e8,0,false,0x1234,0xff80000081ULL,0x1234,0x8100,0x800,0,0x800},
		{0xf3f8,0,false,0x1234,0xff80000081ULL,0x1234,0x800000,0,0x800,0x800},
		{0xf330,0xff0,true,0x1234,0xffab12cd34ULL,0x1234,0xd30,0x800,0x800,0x800},
		{0xf130,0xf0f0,true,0xffabcd1234ULL,0x5678,0xffabcd1234ULL,0x1030,0x800,0x800,0x800},
		{0xf3c8,0,false,0x12345678,0x8080000001ULL,0x12345678,0x0080000101ULL,0x800,0x800,0x800},
		{0xf030,0xf0,true,0x1234,0,0x30,0,0x800,0,0},
		{0xf040,0xf0,true,0xff00000000ULL,0,0xff000000f0ULL,0,0x800,0,0},
		{0xf065,0xff,true,0xff00000000ULL,0,0xff00ff0000ULL,0,0x800,0,0},
		{0xf493,0,false,0xff12345678ULL,0x5678,0x00edcba987ULL,0x5678,0x800,0x800,0x800},
		{0xf0e8,0,false,0xff81000081ULL,0x5678,0x8100,0x5678,0,0x800,0x800},
		{0xf0f8,0,false,0xff12348180ULL,0x5678,0x123481,0x5678,0,0x800,0x800},
		{0xf0c8,0,false,0x01020304,0,0x0103010704ULL,0,0x800,0,0},
		{0xf0ff,0,false,0x80000003,0,0x40000001,0,0,0x800,0x800},
		{0xf1c0,0,false,0xff0000000fULL,0xabcd0000,0xff0000000fULL,0xffabcd000fULL,0x800,0x800,0xffff},
		{0xf1b8,0,false,0xff80000000ULL,0x1234,0xff80000000ULL,0x00ff801234ULL,0x800,0x800,0xffff},
		{0xf468,0,false,0x800000,0,0x80000000,0,0,0x400,0x400},
		{0xf2a0,0,false,0xf0,0xff0000000fULL,0xff000000ffULL,0xff0000000fULL,0x800,0x800,0xffff}
	};
	std::vector<clocked_register_case> cases;
	for (auto const &v : rows) {
		auto initial = initial_case("atomic-register-logic-boundary", {v.opcode,v.extended ? v.literal : u16(0xf4e1),0xf4e1});
		initial.program.push_back({0x5ff,0xf495});
		initial.initial.insert(initial.initial.end(), {{STATE_GENPC,0x5ff},{r::STATE_A,v.a},{r::STATE_B,v.b},{r::STATE_ST0,v.st0},{r::STATE_ST1,0x100}});
		auto final = observation("literal-guard-width-and-carry-outcome", {{STATE_GENPC,v.extended ? 0x603U : 0x602U},
			{r::STATE_A,v.out_a},{r::STATE_B,v.out_b},{r::STATE_ST1,0x100}});
		if (v.mask) final.expected.push_back({r::STATE_ST0,v.flags,v.mask});
		clocked_register_case c{{{0,std::move(initial)},{1,observation("pre-logic-snapshot", {{r::STATE_A,v.a},{r::STATE_B,v.b}})},
			{2,observation("logic-running", {})},{32,std::move(final)}},1,32};
		c.pipeline_frontend = false; c.forbid_data_access = true;
		cases.push_back(std::move(c));
	}
	return cases;
}
}
