#include "c54x_section_common.h"
namespace c54x_test {
inline std::vector<clocked_register_case> section_cases()
{
	struct row {
		u16 opcode,st1,t; u64 a,b,out_a,out_b; u16 out_t;
		std::array<u16,4> pointers,final_pointers;
		u16 xaddress,x,yaddress,y; bool store; u16 stored;
	};
	constexpr row rows[]{
		{0xb03a,0,0,10,20,4,20,0xfffe,{0x1000,0x1100,0xc00,0xb00},{0x1000,0x1100,0xc01,0xb00},0xb00,0xfffe,0xc00,3,false,0},
		{0xb3be,0,0,4,20,4,8,0xfffd,{0x1000,0x1100,0xc03,0xb00},{0x1000,0x1100,0xc00,0xb01},0xb00,0xfffd,0xc03,4,false,0},
		{0xb0be,0,0,20,9,8,9,0xfffd,{0x1000,0x1100,0xc03,0xb00},{0x1000,0x1100,0xc00,0xb01},0xb00,0xfffd,0xc03,4,false,0},
		{0xe2e4,0x100,0xfffd,0x30000,10,0xfffffe0000ULL,19,0xfffd,{0xd00,0x1100,0xc03,0xb00},{0xcff,0x1100,0xc00,0xb00},0xc03,5,0xd00,7,false,0},
		{0xe245,0x100,0x2222,0x30000,10,0xfffff40000ULL,19,0x2222,{0xc10,0xd10,0x1200,0x1300},{0xc0f,0xd0f,0x1200,0x1300},0xc10,0xfffb,0xd10,7,false,0},
		{0xe249,0x140,0x2222,0x30000,10,0xfffff40000ULL,28,0x2222,{0xc10,0xd10,0x1200,0x1300},{0xc0f,0xd11,0x1200,0x1300},0xc10,0xfffb,0xd10,7,false,0},
		{0xa5be,0,0,0x1234,0,0x1234,0xfffffffffaULL,0xfffe,{0x1000,0x1100,0xc03,0xb00},{0x1000,0x1100,0xc00,0xb01},0xb00,0xfffe,0xc03,3,false,0},
		{0xb736,0,0,0x1234,0x8000,0x1234,0x10000,3,{0x1000,0x1100,0xc03,0xb00},{0x1000,0x1100,0xc02,0xb00},0xb00,3,0xc03,4,false,0},
		{0xb43e,0,0,0x8008,0x12345678,0x10000,0x12345678,0xfffe,{0x1000,0x1100,0xc03,0xb00},{0x1000,0x1100,0xc00,0xb00},0xb00,0xfffe,0xc03,4,false,0},
		{0xd6e1,0,4,0x8008,0x12345678,0x10000,0x12345678,4,{0x1000,0xd00,0xc03,0xb00},{0x1000,0xd00,0xc00,0xb00},0xc03,0xfffe,0xd00,0,true,0x1234},
		{0xd6e9,0,4,0x8008,0x12345678,0x10000,0x12345678,4,{0x1000,0xd00,0xc03,0xb00},{0x1000,0xd01,0xc00,0xb00},0xc03,0xfffe,0xd00,0,true,0x1234}
	};
	std::vector<clocked_register_case> cases;
	for (auto const &v : rows) {
		auto initial = initial_case("atomic-dual-address-literal", {v.opcode,0xf4e1});
		initial.program.push_back({0x5ff,0xf495});
		initial.data = {{v.xaddress,v.x},{v.yaddress,v.y}};
		initial.initial.insert(initial.initial.end(), {{STATE_GENPC,0x5ff},{r::STATE_A,v.a},{r::STATE_B,v.b},{r::STATE_T,v.t},
			{r::STATE_ST0,0},{r::STATE_ST1,v.st1},{r::STATE_AR0,1},{r::STATE_BK,4}});
		for (unsigned i = 0; i < 4; ++i) initial.initial.push_back({int(r::STATE_AR2) + int(i),v.pointers[i]});
		auto final = observation("signed-circular-and-independent-pointer-outcome", {{STATE_GENPC,0x602},{r::STATE_A,v.out_a},
			{r::STATE_B,v.out_b},{r::STATE_T,v.out_t},{r::STATE_ST1,v.st1},{r::STATE_AR0,1},{r::STATE_BK,4}},
			{{v.xaddress,v.x},{v.yaddress,v.store ? v.stored : v.y}});
		for (unsigned i = 0; i < 4; ++i) final.expected.push_back({int(r::STATE_AR2) + int(i),v.final_pointers[i]});
		clocked_register_case c{{{0,std::move(initial)},{1,observation("pre-operation-snapshot", {{r::STATE_A,v.a},{r::STATE_B,v.b}})},
			{2,observation("operation-running", {})},{32,std::move(final)}},1,32};
		c.pipeline_frontend = false;
		c.data_events = std::vector<clocked_data_event>{{false,v.xaddress,v.x,0,false},
			{v.store,v.yaddress,v.store ? v.stored : v.y,0,false}};
		cases.push_back(std::move(c));
	}
	return cases;
}
}
